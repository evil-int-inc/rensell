export function formatBrowseCount(
  count: number,
  noun: keyof typeof countNouns,
  language: Language,
  locale: string,
) {
  const [one, few, other] = countNouns[noun][language];
  const rule = new Intl.PluralRules(locale).select(count);
  const word = rule === "one" ? one : rule === "few" ? few : other;
  return `${new Intl.NumberFormat(locale).format(count)} ${word}`;
}
